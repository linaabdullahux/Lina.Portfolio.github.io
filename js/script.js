/* ---------- ANIMATED STAT COUNTERS ---------- */
const counterEls = document.querySelectorAll('.stat .num[data-target]');
const counterObserver = new IntersectionObserver((entries)=>{
  entries.forEach(entry=>{
    if(!entry.isIntersecting) return;
    const el = entry.target;
    const target = parseInt(el.getAttribute('data-target'), 10);
    const suffix = el.getAttribute('data-suffix') || '';
    const pad = el.getAttribute('data-pad') === 'true';
    const duration = 1400;
    const start = performance.now();
    function tick(now){
      const p = Math.min((now - start) / duration, 1);
      const val = Math.floor(p * target);
      el.textContent = (pad ? String(val).padStart(2, '0') : String(val)) + suffix;
      if(p < 1){ requestAnimationFrame(tick); }
      else{ el.textContent = (pad ? String(target).padStart(2, '0') : String(target)) + suffix; }
    }
    requestAnimationFrame(tick);
    counterObserver.unobserve(el);
  });
}, {threshold:0.6});
counterEls.forEach(el=>counterObserver.observe(el));

/* ---------- POINTER-ONLY EFFECTS (cursor, magnetic buttons, tilt) ---------- */
const finePointer = window.matchMedia('(pointer:fine)').matches;
const reducedMotion = window.matchMedia('(prefers-reduced-motion: reduce)').matches;

if(finePointer && !reducedMotion){
  // custom cursor ring
  const ring = document.getElementById('cursorRing');
  window.addEventListener('mousemove', (e)=>{
    ring.style.left = e.clientX + 'px';
    ring.style.top = e.clientY + 'px';
  });
  document.querySelectorAll('a, button, .skill-card, .project-card, .project-featured').forEach(el=>{
    el.addEventListener('mouseenter', ()=>ring.classList.add('hover'));
    el.addEventListener('mouseleave', ()=>ring.classList.remove('hover'));
  });

  // magnetic buttons
  document.querySelectorAll('.btn').forEach(btn=>{
    btn.addEventListener('mousemove', (e)=>{
      const r = btn.getBoundingClientRect();
      const x = e.clientX - r.left - r.width / 2;
      const y = e.clientY - r.top - r.height / 2;
      btn.style.transform = `translate(${x * 0.16}px, ${y * 0.35}px)`;
    });
    btn.addEventListener('mouseleave', ()=>{ btn.style.transform = ''; });
  });

  // parallax tilt on hero frame
  const frameWrap = document.querySelector('.frame-wrap');
  const frame = document.querySelector('.design-frame');
  if(frameWrap && frame){
    frameWrap.addEventListener('mousemove', (e)=>{
      const r = frameWrap.getBoundingClientRect();
      const px = (e.clientX - r.left) / r.width - 0.5;
      const py = (e.clientY - r.top) / r.height - 0.5;
      frame.style.transform = `rotateY(${px * 12}deg) rotateX(${-py * 12}deg)`;
    });
    frameWrap.addEventListener('mouseleave', ()=>{ frame.style.transform = ''; });
  }
}
