/* ---------- CONTACT FORM ---------- */
const contactForm = document.getElementById('contactForm');
const formStatus = document.getElementById('formStatus');

if(contactForm && formStatus){
  contactForm.addEventListener('submit', async (event)=>{
    event.preventDefault();

    const submitButton = contactForm.querySelector('button[type="submit"]');
    const currentLang = document.documentElement.getAttribute('data-lang') || 'en';
    const originalText = submitButton.textContent;

    submitButton.disabled = true;
    submitButton.textContent = currentLang === 'ar' ? 'جاري الإرسال...' : 'Sending...';
    formStatus.className = 'form-note';
    formStatus.textContent = currentLang === 'ar' ? 'جاري إرسال رسالتك...' : 'Sending your message...';

    try{
      // FormSubmit AJAX endpoint: keeps the visitor on the same page.
      const formData = Object.fromEntries(new FormData(contactForm).entries());
      // Make Reply in the received email go directly to the visitor's email.
      formData._replyto = formData.email;

      const response = await fetch(contactForm.action, {
        method: 'POST',
        headers: {
          'Content-Type': 'application/json',
          'Accept': 'application/json'
        },
        body: JSON.stringify(formData)
      });

      const result = await response.json().catch(() => ({}));
      if(!response.ok || result.success === false) {
        throw new Error(result.message || 'Form submission failed');
      }

      contactForm.reset();
      formStatus.className = 'form-note form-success';
      formStatus.textContent = translations[currentLang]['form.success'];
    }catch(error){
      formStatus.className = 'form-note form-error';
      formStatus.textContent = translations[currentLang]['form.error'];
    }finally{
      submitButton.disabled = false;
      submitButton.textContent = translations[currentLang]['form.submit'] || originalText;
    }
  });
}

