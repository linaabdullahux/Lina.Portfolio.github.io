/* ---------- STAR FIELD + CODE SYMBOLS (canvas) ---------- */
(function(){
  const cv=document.getElementById('stars'); if(!cv) return;
  const ctx=cv.getContext('2d'); let W,H,dpr=Math.min(devicePixelRatio||1,2);
  const mouse={x:-999,y:-999}; const R=Math.random;
  const glyphs=['{ }','</>','=>','01','[ ]','( )','&&','#','fn()','<div/>','npm','git'];
  let stars=[],codes=[],shoots=[];
  function size(){W=innerWidth;H=innerHeight;cv.width=W*dpr;cv.height=H*dpr;ctx.setTransform(dpr,0,0,dpr,0,0);
    const n=Math.round(W*H/9000);
    stars=Array.from({length:n},()=>({x:R()*W,y:R()*H,r:R()*1.5+.4,vx:(R()-.5)*.12,vy:(R()-.5)*.12,ph:R()*6.28,sp:.01+R()*.03,g:R()<.22,big:R()<.06}));
    codes=Array.from({length:Math.max(8,Math.round(W/110))},()=>({x:R()*W,y:R()*H,t:glyphs[(R()*glyphs.length)|0],vy:-(.1+R()*.25),s:11+R()*7,a:.1+R()*.16,ph:R()*6.28}));}
  addEventListener('resize',size); size();
  addEventListener('mousemove',e=>{mouse.x=e.clientX;mouse.y=e.clientY;},{passive:true});
  function sparkle(x,y,r,col,a){ctx.save();ctx.translate(x,y);ctx.globalAlpha=a;ctx.fillStyle=col;ctx.beginPath();
    ctx.moveTo(0,-r);ctx.quadraticCurveTo(0,0,r,0);ctx.quadraticCurveTo(0,0,0,r);ctx.quadraticCurveTo(0,0,-r,0);ctx.quadraticCurveTo(0,0,0,-r);ctx.fill();ctx.restore();}
  function frame(){
    const dark=document.documentElement.getAttribute('data-theme')==='dark';
    const teal=dark?'30,138,114':'20,107,90', gold='226,166,59', k=dark?1:.75;
    ctx.clearRect(0,0,W,H);
    for(const s of stars){
      s.x+=s.vx;s.y+=s.vy;s.ph+=s.sp; if(s.x<0)s.x=W;if(s.x>W)s.x=0;if(s.y<0)s.y=H;if(s.y>H)s.y=0;
      const tw=.35+.65*Math.abs(Math.sin(s.ph)), col=s.g?gold:'rgb('+teal+')';
      if(s.big) sparkle(s.x,s.y,s.r*5,col,tw*.9*k); else {ctx.globalAlpha=tw*.8*k;ctx.fillStyle=col;ctx.beginPath();ctx.arc(s.x,s.y,s.r,0,6.28);ctx.fill();}
    }
    ctx.globalAlpha=1;
    // constellation lines near the pointer
    for(let i=0;i<stars.length;i++){const a=stars[i],dm=Math.hypot(a.x-mouse.x,a.y-mouse.y); if(dm>170)continue;
      ctx.strokeStyle='rgba('+teal+','+(.5*(1-dm/170)*k)+')';ctx.lineWidth=.8;ctx.beginPath();ctx.moveTo(a.x,a.y);ctx.lineTo(mouse.x,mouse.y);ctx.stroke();
      for(let j=i+1;j<stars.length;j++){const b=stars[j],d=Math.hypot(a.x-b.x,a.y-b.y); if(d<95&&Math.hypot(b.x-mouse.x,b.y-mouse.y)<170){
        ctx.strokeStyle='rgba('+gold+','+(.35*(1-d/95)*k)+')';ctx.beginPath();ctx.moveTo(a.x,a.y);ctx.lineTo(b.x,b.y);ctx.stroke();}}}
    // floating code symbols
    ctx.font='500 13px JetBrains Mono, monospace';
    for(const c of codes){c.y+=c.vy;c.ph+=.02;if(c.y<-30){c.y=H+20;c.x=R()*W;}
      ctx.font='500 '+c.s+'px JetBrains Mono, monospace';ctx.globalAlpha=c.a*k*(.7+.3*Math.sin(c.ph));ctx.fillStyle='rgb('+teal+')';ctx.fillText(c.t,c.x+Math.sin(c.ph)*8,c.y);}
    // shooting stars
    if(R()<.004)shoots.push({x:R()*W,y:R()*H*.5,vx:6+R()*4,vy:3+R()*2,l:1});
    shoots=shoots.filter(s=>s.l>0);
    for(const s of shoots){s.x+=s.vx;s.y+=s.vy;s.l-=.02;const g=ctx.createLinearGradient(s.x,s.y,s.x-s.vx*9,s.y-s.vy*9);
      g.addColorStop(0,'rgba('+gold+','+s.l+')');g.addColorStop(1,'rgba('+gold+',0)');ctx.globalAlpha=1;ctx.strokeStyle=g;ctx.lineWidth=2;ctx.beginPath();ctx.moveTo(s.x,s.y);ctx.lineTo(s.x-s.vx*9,s.y-s.vy*9);ctx.stroke();}
    ctx.globalAlpha=1;
    if(!reducedMotion)requestAnimationFrame(frame);
  }
  frame();
})();
